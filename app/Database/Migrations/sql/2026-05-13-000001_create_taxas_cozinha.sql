CREATE TABLE IF NOT EXISTS `taxas_cozinha` (
  `id` INT(11) UNSIGNED NOT NULL AUTO_INCREMENT,
  `operacional_id` INT(10) UNSIGNED NOT NULL,
  `cliente` VARCHAR(255) NULL,
  `responsavel_id` INT(10) UNSIGNED NULL,
  `valor_taxa` DECIMAL(15,2) NULL,
  `embutida_contrato` TINYINT(1) NOT NULL DEFAULT 0,
  `houve_negociacao` TINYINT(1) NOT NULL DEFAULT 0,
  `detalhes_negociacao` TEXT NULL,
  `status_financeiro` VARCHAR(20) NOT NULL DEFAULT 'pendente',
  `forma_pagamento` VARCHAR(40) NULL,
  `valor_pago` DECIMAL(15,2) NULL,
  `data_pagamento` DATE NULL,
  `comprovante` VARCHAR(255) NULL,
  `cobranca_realizada` TINYINT(1) NOT NULL DEFAULT 0,
  `data_cobranca` DATE NULL,
  `observacoes` TEXT NULL,
  `responsavel_pagamento` VARCHAR(40) NULL,
  `prevista_contrato` TINYINT(1) NOT NULL DEFAULT 0,
  `created_at` DATETIME NULL,
  `updated_at` DATETIME NULL,
  PRIMARY KEY (`id`),
  KEY `taxas_cozinha_operacional_id_foreign` (`operacional_id`),
  KEY `taxas_cozinha_status_financeiro_foreign` (`status_financeiro`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
